#!/usr/bin/env python3
"""Builds js/questions.js from the hand-written cards in scripts/cards/*.json.

Usage: generate_questions.py [output_path]

{player} / {player2} are resolved at runtime in the browser. The lint must
pass first. The global is still named PICOLO_QUESTIONS because app.js reads it.
"""
import json
import os
import sys

from cardlib import load_cards, lint

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "js", "questions.js")

cards = load_cards()
errors = lint(cards)
if errors:
    for e in errors:
        print("FAIL", e)
    raise SystemExit("Lint failed, not writing questions.js")
if not cards:
    raise SystemExit("No cards found in scripts/cards/")

out = []
for c in cards:
    item = {"text": c["text"], "category": c["category"], "players": c["players"],
            "heat": c["heat"], "pack": c["pack"]}
    for k in ("id", "ends", "endedBy"):
        if k in c:
            item[k] = c[k]
    out.append(item)

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// Auto-generated by scripts/generate_questions.py from scripts/cards/*.json. Do not hand-edit.\n")
    f.write("// {player} / {player2} are replaced at runtime with random players.\n")
    f.write("const PICOLO_QUESTIONS = ")
    f.write(json.dumps(out, indent=2, ensure_ascii=False))
    f.write(";\n")
print(f"Wrote {len(out)} cards to {out_path}")
